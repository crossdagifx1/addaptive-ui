// @vitest-environment happy-dom
import { describe, it, expect } from 'vitest';
import type { Blueprint } from '@aui/schema';
import { canonicalizeBlueprint, verifyBlueprintSignature } from '../src/signing.js';
import { createAUIClient } from '../src/client.js';

const mockBlueprint: Blueprint = {
  schemaVersion: '1.0',
  blueprintId: 'bp_signed_01',
  pageId: 'landing-home',
  segment: 'default',
  tokens: { 'color.primary': '#00E5FF' },
  layout: { type: 'stack', sections: ['hero'] },
  components: {
    hero: {
      type: 'Hero',
      props: { headline: 'Safe UI' },
    },
  },
  meta: {
    createdAt: '2026-10-22T10:00:00Z',
  },
};

describe('@aui/core > Signed Blueprints Verification', () => {
  it('canonicalizes blueprint deterministically regardless of key order', () => {
    const bp1: Blueprint = { ...mockBlueprint, tokens: { 'color.primary': '#fff', density: 'comfortable' } };
    const bp2: Blueprint = { ...mockBlueprint, tokens: { density: 'comfortable', 'color.primary': '#fff' } };
    expect(canonicalizeBlueprint(bp1)).toBe(canonicalizeBlueprint(bp2));
  });

  it('rejects unsigned blueprints when signature is missing', async () => {
    const result = await verifyBlueprintSignature(mockBlueprint, 'site_sec_secret123');
    expect(result.valid).toBe(false);
    expect(result.reason).toContain('Missing cryptographic signature');
  });

  it('verifies valid HMAC-SHA256 signature generated by Web Crypto or Node', async () => {
    const secret = 'site_sec_secret123';
    const canonical = canonicalizeBlueprint(mockBlueprint);

    const enc = new TextEncoder();
    const key = await globalThis.crypto.subtle.importKey(
      'raw',
      enc.encode(secret),
      { name: 'HMAC', hash: 'SHA-256' },
      false,
      ['sign']
    );
    const sigBytes = await globalThis.crypto.subtle.sign('HMAC', key, enc.encode(canonical));
    const hex = Array.from(new Uint8Array(sigBytes))
      .map((b) => b.toString(16).padStart(2, '0'))
      .join('');

    const signedBp: Blueprint = {
      ...mockBlueprint,
      meta: {
        ...mockBlueprint.meta,
        signature: `sig_sha256_${hex}`,
      },
    };

    const verifyResult = await verifyBlueprintSignature(signedBp, secret);
    expect(verifyResult.valid).toBe(true);

    // Tampered content must fail
    const tamperedBp: Blueprint = {
      ...signedBp,
      components: {
        hero: {
          type: 'Hero',
          props: { headline: 'HACKED CONTENT' },
        },
      },
    };

    const tamperedResult = await verifyBlueprintSignature(tamperedBp, secret);
    expect(tamperedResult.valid).toBe(false);
    expect(tamperedResult.reason).toContain('Signature mismatch');
  });

  it('client rejects tampered blueprint and falls back to default safely', async () => {
    const secret = 'site_sec_secret123';
    const client = createAUIClient({
      siteId: 'site_test',
      apiEndpoint: '',
      signatureKey: secret,
      requireSignedBlueprints: true,
      defaultBlueprint: mockBlueprint,
      renderer: {
        mode: 'hosted-pack',
        useCssVariables: true,
        reserveDimensions: false,
        respectReducedMotion: false,
        respectColorScheme: false,
      },
    });

    // Provide untrusted blueprint without signature
    const untrusted: Blueprint = {
      ...mockBlueprint,
      blueprintId: 'bp_hacked',
    };

    const res = await client.applyBlueprint(untrusted);
    // Should safely fall back or reject
    expect(res.fellBack).toBe(true);
  });
});
